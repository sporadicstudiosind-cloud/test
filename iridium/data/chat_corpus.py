#: Default: commercially usable sources only. Small-model-sized synthetic chat
#: carries most of the weight; the human-written sets keep it honest; worked
#: maths solutions supply the reasoning share.
DEFAULT_CHAT_MIX = {"smol_smoltalk": 0.45, "oasst": 0.20, "dolly": 0.15, "openr1_math": 0.20}

#: Everything registered, opt-in sources included. Private use only unless every
#: source's terms have been checked for the intended use.
MAX_CHAT_MIX = {"smol_smoltalk": 0.30, "ultrachat": 0.20, "tulu3": 0.20, "oasst": 0.10,
                "dolly": 0.05, "openr1_math": 0.15}


def chat_licence_notice(keys=None) -> str:
    lines = ["Conversation corpora and their terms:", ""]
    for key in (keys or DEFAULT_CHAT_MIX):
        spec = CHAT_SOURCES[key]
        lines += [
            f"* {spec.dataset}",
            f"    licence:     {spec.licence}",
            f"    obligation:  {spec.obligation}",
            f"    homepage:    {spec.homepage}",
        ]
    lines += [
        "",
        "These teach the form of a reply, not the truth of one. A fluent answer",
        "from a model this size is still an unverified answer.",
    ]
    return "\n".join(lines)


