@dataclass(frozen=True)
class ChatSourceSpec:
    key: str
    dataset: str
    config: Optional[str]
    split: str
    licence: str
    obligation: str
    description: str
    homepage: str = ""
    approx_rows: int = 10_000
    #: Whether the licence *as stated on the dataset card* permits commercial
    #: use. False also covers "unclear" -- e.g. data generated by a model whose
    #: provider's terms restrict training competing models on its outputs.
    commercial_ok: bool = True
    #: Who wrote the replies: "human", or the model family that generated them.
    #: Distilled data teaches that model's habits and mistakes too.
    written_by: str = "human"
    #: Opt-in sources are registered and loadable, but never in a default mix.
    opt_in: bool = False
    #: Columns to read; ``None`` reads all. Streaming parquet materialises
    #: whole row groups, so skipping a wide unused column (OpenR1's traces)
    #: is the difference between ~1 GB and ~4 GB of host RAM.
    columns: Optional[tuple[str, ...]] = None

    def as_dict(self) -> dict:
        return asdict(self)


